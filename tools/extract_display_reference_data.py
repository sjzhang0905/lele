"""Extract numeric reference facts from locally supplied official distributions.

Usage: python tools/extract_display_reference_data.py REFERENCE_DIRECTORY
Expected: bonds5.bin, gv.bin, elements.ini. Original application files are not
bundled with LELE. See docs/display_reference_data.md for scope and provenance.
"""
from pathlib import Path
import hashlib
import math
import struct
import sys


def extract(directory):
    directory = Path(directory)
    bonds = (directory / 'bonds5.bin').read_bytes()
    assert struct.unpack_from('<I', bonds)[0] == 790, 'Unrecognized bond table version'
    offset = 4
    rows = []
    for first in range(106):
        row = []
        for second in range(first, 106):
            count, = struct.unpack_from('<H', bonds, offset)
            offset += 2
            assert count <= 4
            ordinary = []
            for _ in range(count):
                kind = bonds[offset]
                nominal, squared_limit = struct.unpack_from('<dd', bonds, offset + 8)
                offset += 24
                assert kind in range(5) and math.isfinite(nominal) and squared_limit > 0
                if kind != 4:  # Independent hydrogen-bond records are not ordinary bonds.
                    ordinary.append(squared_limit)
            if first:
                row.append(max(ordinary) if ordinary else None)
        if first:
            rows.append(tuple(row))
    assert len(bonds) - offset == 65, 'Unexpected bond table layout'

    # Chemcraft's own GaussView-style preset, not a Gaussian-authored RGB export.
    scheme = (directory / 'gv.bin').read_bytes()
    assert struct.unpack_from('<I', scheme)[0] == 741
    colors = []
    for index in range(106):
        rgb = struct.unpack_from('<3d', scheme, 135 + 121 * index)
        assert all(math.isfinite(x) and 0 <= x <= 1 for x in rgb)
        colors.append('#' + ''.join(f'{round(x * 255):02X}' for x in rgb))

    radii = {}
    for line in (directory / 'elements.ini').read_text().splitlines():
        fields = line.split()
        assert len(fields) == 8
        # VESTA stores atomic, vdW, ionic (in that order), then its own RGB.
        radii[fields[1]] = tuple(float(x) for x in fields[2:5])
    assert len(radii) == 97
    hashes = {name: hashlib.sha256((directory / name).read_bytes()).hexdigest()
              for name in ('bonds5.bin', 'gv.bin', 'elements.ini')}
    return rows, colors, radii, hashes


def main():
    rows, colors, radii, hashes = extract(sys.argv[1])
    target = Path(__file__).resolve().parents[1] / 'lele' / '_display_reference_values.py'
    text = ('"""Numeric reference facts; generated by tools/extract_display_reference_data.py.\n'
            'See docs/display_reference_data.md. No upstream application files are included.\n"""\n\n'
            f'SOURCE_SHA256 = {hashes!r}\n\n'
            '# Atomic numbers 1..106; Chemcraft GaussView-style compatibility palette.\n'
            f'GAUSSVIEW_STYLE_COLORS = {tuple(colors)!r}\n\n'
            '# Element -> (atomic, van der Waals, representative ionic radius), Angstrom.\n'
            'VESTA_RADII = {\n')
    text += ''.join(f'    {symbol!r}: {values!r},\n' for symbol, values in radii.items())
    text += ('}\n\n# Upper triangle for atomic numbers 1..105, squared ordinary-bond limits.\n'
             '# Row z-1 contains pairs (z,z)..(z,105); None means no ordinary record.\n'
             'CHEMCRAFT_LIMITS_SQUARED = (\n')
    text += ''.join(f'    {row!r},\n' for row in rows)
    target.write_text(text + ')\n', encoding='utf-8')
    print(target)


if __name__ == '__main__':
    main()
