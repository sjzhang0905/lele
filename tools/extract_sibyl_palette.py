"""Extract only the RGB facts and element mapping; never execute the TCL file."""
from hashlib import sha256
from pathlib import Path
import re
import sys


def extract(path):
    data=Path(path).read_bytes();text=data.decode('utf-8-sig')
    rows=re.findall(r'^color change rgb\s+(\d+)\s+([.\d]+)\s+([.\d]+)\s+([.\d]+)\s*$',text,re.M)
    rgb={int(cid):tuple(float(x) for x in values) for cid,*values in rows}
    if len(rgb)!=len(rows) or any(not 0<=x<=1 for values in rgb.values() for x in values):
        raise ValueError('Invalid or duplicate TCL RGB definitions.')
    block=re.search(r'set elem_color_list\s*\{([^}]*)\}',text)
    if block is None:raise ValueError('Missing TCL element-to-color mapping.')
    fields=block[1].split()
    if len(fields)%2:raise ValueError('Incomplete TCL element-to-color mapping.')
    pairs=list(zip(fields[::2],fields[1::2]))
    if len({s for s,_ in pairs})!=len(pairs):raise ValueError('Duplicate mapped element.')
    if any(re.fullmatch(r'[A-Z][a-z]?',s) is None for s,_ in pairs):raise ValueError('Invalid element symbol.')
    return {s:rgb[int(cid)] for s,cid in pairs},sha256(data).hexdigest()


def main():
    values,digest=extract(sys.argv[1])
    path=Path(__file__).resolve().parents[1]/'lele/sibyl_palette.py'
    content=('"""RGB facts from the supplied Sibyl.tcl; H–Rg, plus the H isotope alias D.\n'
             'Generated by tools/extract_sibyl_palette.py. The TCL program is never executed.\n'
             'LELE renders the palette in its existing 8-bit RGB color pipeline.\n"""\n\n'
             f'SOURCE_SHA256 = {digest!r}\n\nSIBYL_RGB = {{\n')
    content+=''.join(f'    {s!r}: {rgb!r},\n' for s,rgb in values.items())
    content+=('}\n\nSIBYL_COLORS = {symbol: "#" + "".join(f"{round(x*255):02X}" for x in values)\n'
              '                for symbol,values in SIBYL_RGB.items()}\n'
              "SIBYL_COLORS['D'] = SIBYL_COLORS['H']\n")
    path.write_text(content,encoding='utf-8')
    print(f'{len(values)} element colors written to {path}')


if __name__=='__main__':main()
