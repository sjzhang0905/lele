"""Lightweight Qt controls; scientific data is loaded after first paint."""
from PySide6.QtCore import Signal
from PySide6.QtWidgets import (QGroupBox, QVBoxLayout, QHBoxLayout, QFormLayout,
                               QLabel, QPushButton, QDoubleSpinBox, QCheckBox)


class VibrationControls(QGroupBox):
    playRequested = Signal()
    stopRequested = Signal()
    amplitudeChanged = Signal()

    def __init__(self, parent=None):
        super().__init__('Vibration', parent)
        layout = QVBoxLayout(self)
        self.description = QLabel()
        self.description.setWordWrap(True)
        layout.addWidget(self.description)
        buttons = QHBoxLayout()
        self.play_button = QPushButton('Pause')
        self.play_button.clicked.connect(self.playRequested)
        buttons.addWidget(self.play_button)
        self.stop_button = QPushButton('Stop / reset')
        self.stop_button.clicked.connect(self.stopRequested)
        buttons.addWidget(self.stop_button)
        layout.addLayout(buttons)
        form = QFormLayout()
        self.amplitude = QDoubleSpinBox()
        self.amplitude.setRange(.01, 2.)
        self.amplitude.setDecimals(2)
        self.amplitude.setSingleStep(.05)
        self.amplitude.setValue(.35)
        self.amplitude.setKeyboardTracking(False)
        self.amplitude.setSuffix(' Å')
        self.amplitude.setToolTip('Maximum atom displacement from the reference geometry.')
        self.amplitude.valueChanged.connect(self.amplitudeChanged)
        form.addRow('Amplitude', self.amplitude)
        self.speed = QDoubleSpinBox()
        self.speed.setRange(.1, 5.)
        self.speed.setDecimals(1)
        self.speed.setSingleStep(.1)
        self.speed.setValue(1.)
        self.speed.setKeyboardTracking(False)
        self.speed.setSuffix(' cycles/s')
        form.addRow('Speed', self.speed)
        self.arrows_check = QCheckBox('Show displacement arrows')
        form.addRow(self.arrows_check)
        self.selected_arrows_check = QCheckBox('Arrows on selected atoms only')
        form.addRow(self.selected_arrows_check)
        self.arrow_length = QDoubleSpinBox()
        self.arrow_length.setRange(.05, 5.); self.arrow_length.setValue(1.)
        self.arrow_length.setDecimals(2); self.arrow_length.setSingleStep(.1)
        self.arrow_length.setSuffix(' Å'); self.arrow_length.setKeyboardTracking(False)
        form.addRow('Maximum arrow length', self.arrow_length)
        layout.addLayout(form)
        note = QLabel('Visual oscillation · coordinates and exports use the reference geometry.')
        note.setWordWrap(True)
        layout.addWidget(note)
        self.hide()
